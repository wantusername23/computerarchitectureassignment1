// This file is where all of the CPU components are assembled into the whole CPU

package dinocpu

import chisel3._
import chisel3.util._
import dinocpu.components._

/**
 * The main CPU definition that hooks up all of the other components.
 *
 * For more information, see section 4.4 of Patterson and Hennessy
 * This follows figure 4.21
 */
class SingleCycleCPU(implicit val conf: CPUConfig) extends BaseCPU {
  // All of the structures required
  val pc         = dontTouch(RegInit(0.U(64.W)))
  val control    = Module(new Control())
  val registers  = Module(new RegisterFile())
  val aluControl = Module(new ALUControl())
  val alu        = Module(new ALU())
  val immGen     = Module(new ImmediateGenerator())
  val nextpc     = Module(new NextPC())
  val (cycleCount, _) = Counter(true.B, 1 << 30)

  //FETCH
  io.imem.address := pc
  io.imem.valid := true.B

  val instruction = Wire(UInt(32.W))
  when ((pc % 8.U) === 4.U) {
    instruction := io.imem.instruction(63, 32)
  } .otherwise {
    instruction := io.imem.instruction(31, 0)
  }

  control.io    := DontCare  // PLACEHOLDER 
  registers.io  := DontCare  // PLACEHOLDER
  aluControl.io := DontCare  // PLACEHOLDER
  alu.io        := DontCare  // PLACEHOLDER
  immGen.io     := DontCare  // PLACEHOLDER
  nextpc.io     := DontCare  // PLACEHOLDER

  // TODO: Connect the modules to build the datapath for R-type and I-type instructions.


  io.dmem := DontCare  // Do not modify
}

/*
 * Object to make it easier to print information about the CPU
 */
object SingleCycleCPUInfo {
  def getModules(): List[String] = {
    List(
      "dmem",
      "imem",
      "control",
      "registers",
      "aluControl",
      "alu",
      "immGen",
      "nextpc"
    )
  }
}
